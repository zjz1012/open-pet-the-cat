export type CoatPatternType =
  | 'solid'
  | 'tabby'
  | 'calico'
  | 'bicolor'
  | 'tortie'
  | 'colorpoint'
  | 'ragdoll'
  | 'sphynx';

export interface CatBreed {
  id: string;
  nameZh: string;
  nameEn: string;
  nameJa: string;
  pattern: CoatPatternType;
  /** Primary coat RGB in linear-ish 0..1 space */
  primaryColor: [number, number, number];
  /** Secondary coat / stripe / patch RGB */
  secondaryColor: [number, number, number];
  /** Tertiary patch / belly / highlight RGB */
  tertiaryColor: [number, number, number];
  /** Inner ear skin/fur tint */
  earInnerColor: [number, number, number];
  /** 0 = hairless Sphynx, 0.45 = sleek shorthair, 0.72 = plush, 1.0 = long shaggy */
  furLength: number;
  /** Fur thickness / clumping factor (0.2 = silky fine, 1.0 = coarse/shaggy) */
  furClump: number;
  /** Specular sheen intensity (higher for sleek black/grey coats) */
  sheen: number;
  /** Pattern scale / seed */
  patternSeed: number;
  /** Tail bushiness multiplier */
  tailFluff: number;
  /** Neck ruff extra fluff (Norwegian / Siberian / Ragdoll) */
  ruffFluff: number;
  /** Purr base frequency in Hz (smaller/sleeker cats slightly higher, big floofs deeper) */
  purrHz: number;
  /** CSS swatch preview styling */
  swatchGradient: string;
}

